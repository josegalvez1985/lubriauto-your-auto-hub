-- entrada sin pisar la que ya está. Se puede correr las veces que haga falta.
--
-- ORDEN DE EJECUCIÓN (SQL Workshop -> SQL Scripts -> Upload -> Run)
--
--   1. ESTE archivo
--   2. backend/asistente.sql
--
-- NOMBRES PROPIOS: el esquema es el mismo del ERP (LUBRIMEC_IA_*) y de la
-- página web (PW_IA_*), que ya tienen su asistente. Todo lo de LubriAuto
-- empieza con LT_ y no toca nada de ellos.
--
-- LA CLAVE DE LA API NO VA ACÁ: el paquete usa la del ERP
-- (LUBRIMEC_IA_CONFIG.API_KEY), así hay una sola copia. Ver asistente.sql.
--------------------------------------------------------------------------------

SET DEFINE OFF
SET SERVEROUTPUT ON

DECLARE
  PROCEDURE ejecutar(p_sql IN VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
  END ejecutar;

  FUNCTION existe(p_tabla IN VARCHAR2) RETURN BOOLEAN IS
    l_c PLS_INTEGER;
  BEGIN
    SELECT COUNT(*) INTO l_c FROM user_tables WHERE table_name = p_tabla;
    IF l_c > 0 THEN
      DBMS_OUTPUT.PUT_LINE('[SKIP] La tabla ' || p_tabla || ' ya existia.');
    END IF;
    RETURN l_c > 0;
  END existe;
BEGIN
  -- Clave / valor. Sin la clave de la API (esa es la del ERP).
  IF NOT existe('LT_IA_CONFIG') THEN
    ejecutar(q'~
      CREATE TABLE LT_IA_CONFIG (
        CLAVE          VARCHAR2(60)   NOT NULL,
        VALOR          VARCHAR2(4000),
        MODIFICADO_EL  DATE DEFAULT SYSDATE NOT NULL,
        CONSTRAINT PK_LT_IA_CONFIG PRIMARY KEY (CLAVE)
      )~');
    ejecutar(q'~COMMENT ON TABLE LT_IA_CONFIG IS 'Configuracion del asistente con IA de LubriAuto: modelo y limites. Privada: la IA no la puede consultar.'~');
    DBMS_OUTPUT.PUT_LINE('[OK]   Tabla LT_IA_CONFIG creada.');
  END IF;

  -- Cada pregunta. Es también el contador de los topes del día: las filas con
  -- ERROR no cuentan. USUARIO es el de LT_AUTOS.USUARIO (el que da el token).
  IF NOT existe('LT_IA_CONSULTAS') THEN
    ejecutar(q'~
      CREATE TABLE LT_IA_CONSULTAS (
        ID                     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
        USUARIO                VARCHAR2(255) NOT NULL,
        FECHA                  DATE          NOT NULL,
        PANTALLA               VARCHAR2(200),
        PREGUNTA               CLOB,
        RESPUESTA              CLOB,
        CONSULTAS              CLOB,
        VUELTAS                NUMBER,
        TOKENS_ENTRADA         NUMBER,
        TOKENS_SALIDA          NUMBER,
        TOKENS_CACHE_LEIDOS    NUMBER,
        TOKENS_CACHE_ESCRITOS  NUMBER,
        MILISEGUNDOS           NUMBER,
        MODELO                 VARCHAR2(60),
        ERROR                  VARCHAR2(4000),
        CONSTRAINT PK_LT_IA_CONSULTAS PRIMARY KEY (ID)
      )~');
    ejecutar('CREATE INDEX IX_LT_IA_CONSULTAS_USR ON LT_IA_CONSULTAS (USUARIO, FECHA)');
    ejecutar('CREATE INDEX IX_LT_IA_CONSULTAS_FEC ON LT_IA_CONSULTAS (FECHA)');
    ejecutar(q'~COMMENT ON TABLE LT_IA_CONSULTAS IS 'Cada pregunta al asistente de LubriAuto: quien, cuando (hora de Paraguay), la respuesta, las consultas SQL que corrio y los tokens. Privada.'~');
    ejecutar(q'~COMMENT ON COLUMN LT_IA_CONSULTAS.CONSULTAS IS 'JSON con las consultas que corrio la IA: [{motivo, sql, filas, error}]. Al usuario no se le muestran.'~');
    DBMS_OUTPUT.PUT_LINE('[OK]   Tabla LT_IA_CONSULTAS creada.');
  END IF;

  -- Los valores de entrada. Los que ya están no se tocan.
  --   LIMITE_DIARIO         preguntas por usuario y por día
  --   LIMITE_GLOBAL_DIARIO  preguntas de TODO LubriAuto por día: el registro es
  --                         abierto y la clave es la del ERP (mismo tope de
  --                         gasto mensual); esto evita que LubriAuto lo agote.
  FOR c IN (SELECT 'MODELO' AS clave, 'claude-haiku-5-5' AS valor FROM dual
            UNION ALL SELECT 'ESFUERZO', 'low' FROM dual
            UNION ALL SELECT 'LIMITE_DIARIO', '10' FROM dual
            UNION ALL SELECT 'LIMITE_GLOBAL_DIARIO', '50' FROM dual
            UNION ALL SELECT 'MAX_FILAS', '200' FROM dual) LOOP
    EXECUTE IMMEDIATE q'~
      MERGE INTO lt_ia_config t
      USING (SELECT :1 AS clave, :2 AS valor FROM dual) s
         ON (t.clave = s.clave)
       WHEN NOT MATCHED THEN INSERT (clave, valor) VALUES (s.clave, s.valor)~'
      USING c.clave, c.valor;
  END LOOP;
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('[OK]   LT_IA_CONFIG con sus valores de entrada.');
END;
