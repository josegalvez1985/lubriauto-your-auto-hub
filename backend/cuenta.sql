--------------------------------------------------------------------------------
-- LubriAuto · BAJA Y REACTIVACIÓN DE CUENTA
--
-- El usuario da de baja su propia cuenta desde Ajustes, y la reactiva él mismo
-- desde "Regístrate gratis" con el mismo correo:
--
--   POST /lt/cuenta/inactivar          Bearer  { password, motivo }
--        -> { ok, mensaje }
--   POST /lt/cuenta/estado             { email }
--        -> { ok, inactiva }           ¿ese correo tiene una cuenta dada de baja?
--   POST /lt/cuenta/reactivar          { email, password }
--        -> { ok, mensaje }            con la contraseña de la cuenta
--   POST /lt/cuenta/reactivar-correo   { email }
--        -> { ok, mensaje }            le manda una contraseña nueva al correo
--   Errores: { ok: false, error }
--
-- QUÉ HACE (22/10/2026):
--
--   - BAJA: LT_USUARIOS.ESTADO = 'I' (PKG_AUTH.pr_login ya rechaza ese estado)
--     y revoca TODOS sus tokens (ESTADO = 'R', como PKG_AUTH.pr_revocar_token):
--     PKG_AUTOS.fn_usuario no mira el estado del usuario, solo el del token.
--     NO borra nada: sus vehículos y servicios quedan.
--   - REACTIVACIÓN, siempre probando que la cuenta es suya:
--       · con la contraseña de la cuenta (tope de PKG_AUTH.c_max_intentos
--         intentos fallidos, que cuentan en INTENTOS_FALLIDOS como en el login);
--       · o con una contraseña nueva enviada al correo, como pr_reset_password
--         (que no trabaja con cuentas 'I'). Esta respuesta es siempre la misma,
--         exista o no la cuenta.
--   - LT_CUENTAS_BAJAS guarda cada baja (con el motivo) y cuándo y cómo se
--     reactivó.
--
--   El administrador también puede reactivar a mano:
--     UPDATE LT_USUARIOS SET ESTADO = 'A', FECHA_MODIF = SYSTIMESTAMP
--      WHERE USERNAME = '...';
--     COMMIT;
--
-- NO TOCA PKG_AUTH ni PKG_AUTOS: usa sus funciones públicas (fn_usuario,
-- fn_hash_password, fn_generar_salt, fn_password_aleatoria, pr_enviar_correo,
-- pr_flush_correo). Del módulo ORDS `lt` SOLO agrega las plantillas cuenta/*,
-- sin redefinirlo.
--
-- Se puede correr las veces que haga falta.
--------------------------------------------------------------------------------

SET DEFINE OFF
SET SERVEROUTPUT ON


--------------------------------------------------------------------------------
-- 1. LT_CUENTAS_BAJAS (si falta, y sus columnas nuevas)
--------------------------------------------------------------------------------

DECLARE
  l_c PLS_INTEGER;

  PROCEDURE columna(p_nombre IN VARCHAR2, p_tipo IN VARCHAR2) IS
    l_n PLS_INTEGER;
  BEGIN
    SELECT COUNT(*) INTO l_n FROM user_tab_columns
     WHERE table_name = 'LT_CUENTAS_BAJAS' AND column_name = p_nombre;
    IF l_n = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE LT_CUENTAS_BAJAS ADD (' || p_nombre || ' ' || p_tipo || ')';
      DBMS_OUTPUT.PUT_LINE('[OK]   Columna LT_CUENTAS_BAJAS.' || p_nombre || ' agregada.');
    END IF;
  END columna;
BEGIN
  SELECT COUNT(*) INTO l_c FROM user_tables WHERE table_name = 'LT_CUENTAS_BAJAS';
  IF l_c > 0 THEN
    DBMS_OUTPUT.PUT_LINE('[SKIP] La tabla LT_CUENTAS_BAJAS ya existia.');
  ELSE
    EXECUTE IMMEDIATE q'~
      CREATE TABLE LT_CUENTAS_BAJAS (
        ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
        ID_USUARIO  NUMBER        NOT NULL,
        USERNAME    VARCHAR2(150) NOT NULL,
        FECHA       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        MOTIVO      VARCHAR2(1000),
        CONSTRAINT PK_LT_CUENTAS_BAJAS PRIMARY KEY (ID)
      )~';
    EXECUTE IMMEDIATE q'~COMMENT ON TABLE LT_CUENTAS_BAJAS IS 'Cuentas que el usuario dio de baja desde la app (LT_USUARIOS.ESTADO = I), con el motivo si lo dio, y si la reactivo.'~';
    DBMS_OUTPUT.PUT_LINE('[OK]   Tabla LT_CUENTAS_BAJAS creada.');
  END IF;

  columna('FECHA_REACTIVACION', 'TIMESTAMP');
  columna('MEDIO_REACTIVACION', 'VARCHAR2(20)');  -- CONTRASENA o CORREO
END;
/


--------------------------------------------------------------------------------
-- 2. PKG_LT_CUENTA
--------------------------------------------------------------------------------

CREATE OR REPLACE PACKAGE PKG_LT_CUENTA AS

  -- Da de baja la cuenta del dueño del token si la contraseña es la suya.
  -- -20401 token inválido (de PKG_AUTOS.fn_usuario) · -20003 contraseña
  -- incorrecta · -20004 usuario no encontrado o ya inactivo.
  PROCEDURE pr_inactivar (
    p_token    IN VARCHAR2,
    p_password IN VARCHAR2,
    p_motivo   IN VARCHAR2 DEFAULT NULL
  );

  -- 'S' si el correo (o usuario) tiene una cuenta dada de baja, si no 'N'.
  FUNCTION fn_inactiva (p_email IN VARCHAR2) RETURN VARCHAR2;

  -- Reactiva una cuenta dada de baja con su contraseña. Hace COMMIT de los
  -- intentos fallidos antes de lanzar (como PKG_AUTH.pr_login).
  -- -20008 no hay cuenta dada de baja · -20009 demasiados intentos ·
  -- -20003 contraseña incorrecta.
  PROCEDURE pr_reactivar (p_email IN VARCHAR2, p_password IN VARCHAR2);

  -- Reactiva una cuenta dada de baja con una contraseña nueva que se manda al
  -- correo (encolada: llamar PKG_AUTH.pr_flush_correo después del COMMIT). Si
  -- no hay cuenta dada de baja no hace nada, sin avisar.
  PROCEDURE pr_reactivar_correo (p_email IN VARCHAR2);

END PKG_LT_CUENTA;
/

CREATE OR REPLACE PACKAGE BODY PKG_LT_CUENTA AS

  -- La última baja sin reactivar de ese usuario queda marcada. Si lo dio de
  -- baja el administrador a mano, no hay fila y no pasa nada.
  PROCEDURE marcar_reactivacion(p_id_usuario IN NUMBER, p_medio IN VARCHAR2) IS
  BEGIN
    UPDATE LT_CUENTAS_BAJAS
       SET FECHA_REACTIVACION = SYSTIMESTAMP,
           MEDIO_REACTIVACION = p_medio
     WHERE ID = (SELECT MAX(ID) FROM LT_CUENTAS_BAJAS
                  WHERE ID_USUARIO = p_id_usuario AND FECHA_REACTIVACION IS NULL);
  END marcar_reactivacion;

  ------------------------------------------------------------------------------
  PROCEDURE pr_inactivar (
    p_token    IN VARCHAR2,
    p_password IN VARCHAR2,
    p_motivo   IN VARCHAR2 DEFAULT NULL
  ) IS
    l_username LT_USUARIOS.USERNAME%TYPE;
    l_id       LT_USUARIOS.ID_USUARIO%TYPE;
    l_salt     LT_USUARIOS.SALT%TYPE;
    l_hash     LT_USUARIOS.PASSWORD_HASH%TYPE;
  BEGIN
    -- El usuario sale del token, nunca del body.
    l_username := PKG_AUTOS.fn_usuario(p_token);

    BEGIN
      SELECT ID_USUARIO, SALT, PASSWORD_HASH
        INTO l_id, l_salt, l_hash
        FROM LT_USUARIOS
       WHERE USERNAME = l_username
         AND ESTADO = 'A'
         FOR UPDATE;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20004, 'Usuario no encontrado o inactivo.');
    END;

    IF p_password IS NULL OR PKG_AUTH.fn_hash_password(p_password, l_salt) <> l_hash THEN
      RAISE_APPLICATION_ERROR(-20003, 'La contraseña es incorrecta.');
    END IF;

    UPDATE LT_USUARIOS
       SET ESTADO      = 'I',
           FECHA_MODIF = SYSTIMESTAMP
     WHERE ID_USUARIO = l_id;

    -- Cierra todas sus sesiones, en todos los dispositivos.
    UPDATE LT_TOKENS
       SET ESTADO = 'R'
     WHERE ID_USUARIO = l_id
       AND ESTADO = 'A';

    INSERT INTO LT_CUENTAS_BAJAS (ID_USUARIO, USERNAME, MOTIVO)
    VALUES (l_id, l_username, SUBSTR(TRIM(p_motivo), 1, 1000));
  END pr_inactivar;

  ------------------------------------------------------------------------------
  FUNCTION fn_inactiva (p_email IN VARCHAR2) RETURN VARCHAR2 IS
    l_n PLS_INTEGER;
  BEGIN
    SELECT COUNT(*) INTO l_n
      FROM LT_USUARIOS
     WHERE (EMAIL = LOWER(TRIM(p_email)) OR USERNAME = LOWER(TRIM(p_email)))
       AND ESTADO = 'I';
    RETURN CASE WHEN l_n > 0 THEN 'S' ELSE 'N' END;
  END fn_inactiva;

  ------------------------------------------------------------------------------
  PROCEDURE pr_reactivar (p_email IN VARCHAR2, p_password IN VARCHAR2) IS
    l_id       LT_USUARIOS.ID_USUARIO%TYPE;
    l_salt     LT_USUARIOS.SALT%TYPE;
    l_hash     LT_USUARIOS.PASSWORD_HASH%TYPE;
    l_intentos NUMBER;
  BEGIN
    BEGIN
      SELECT ID_USUARIO, SALT, PASSWORD_HASH, NVL(INTENTOS_FALLIDOS, 0)
        INTO l_id, l_salt, l_hash, l_intentos
        FROM LT_USUARIOS
       WHERE (EMAIL = LOWER(TRIM(p_email)) OR USERNAME = LOWER(TRIM(p_email)))
         AND ESTADO = 'I'
         FOR UPDATE;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20008, 'No hay una cuenta dada de baja con ese correo.');
    END;

    IF l_intentos >= PKG_AUTH.c_max_intentos THEN
      RAISE_APPLICATION_ERROR(-20009, 'Demasiados intentos. Pide que te enviemos una contraseña nueva al correo.');
    END IF;

    IF p_password IS NULL OR PKG_AUTH.fn_hash_password(p_password, l_salt) <> l_hash THEN
      UPDATE LT_USUARIOS SET INTENTOS_FALLIDOS = l_intentos + 1 WHERE ID_USUARIO = l_id;
      COMMIT;  -- que el intento quede aunque el handler haga ROLLBACK
      RAISE_APPLICATION_ERROR(-20003, 'La contraseña no coincide con la de tu cuenta.');
    END IF;

    UPDATE LT_USUARIOS
       SET ESTADO            = 'A',
           INTENTOS_FALLIDOS = 0,
           FECHA_MODIF       = SYSTIMESTAMP
     WHERE ID_USUARIO = l_id;

    marcar_reactivacion(l_id, 'CONTRASENA');
  END pr_reactivar;

  ------------------------------------------------------------------------------
  PROCEDURE pr_reactivar_correo (p_email IN VARCHAR2) IS
    l_id     LT_USUARIOS.ID_USUARIO%TYPE;
    l_user   LT_USUARIOS.USERNAME%TYPE;
    l_nombre LT_USUARIOS.NOMBRE_COMPLETO%TYPE;
    l_correo LT_USUARIOS.EMAIL%TYPE;
    l_nueva  VARCHAR2(20);
    l_salt   VARCHAR2(32);
  BEGIN
    BEGIN
      SELECT ID_USUARIO, USERNAME, NOMBRE_COMPLETO, EMAIL
        INTO l_id, l_user, l_nombre, l_correo
        FROM LT_USUARIOS
       WHERE (EMAIL = LOWER(TRIM(p_email)) OR USERNAME = LOWER(TRIM(p_email)))
         AND ESTADO = 'I'
         FOR UPDATE;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RETURN;  -- no se revela si hay una cuenta
    END;

    l_nueva := PKG_AUTH.fn_password_aleatoria(10);
    l_salt  := PKG_AUTH.fn_generar_salt;

    UPDATE LT_USUARIOS
       SET PASSWORD_HASH     = PKG_AUTH.fn_hash_password(l_nueva, l_salt),
           SALT              = l_salt,
           ESTADO            = 'A',
           INTENTOS_FALLIDOS = 0,
           FECHA_MODIF       = SYSTIMESTAMP
     WHERE ID_USUARIO = l_id;

    marcar_reactivacion(l_id, 'CORREO');

    PKG_AUTH.pr_enviar_correo(
      p_destino => l_correo,
      p_asunto  => 'Reactivación de tu cuenta - Lubrimec, Lubricantes y Filtros',
      p_cuerpo  => 'Hola ' || NVL(l_nombre, l_user) || ',' || CHR(10) || CHR(10) ||
                   'Tu cuenta de LubriAuto fue reactivada: tus vehículos y servicios siguen ahí.' || CHR(10) ||
                   'Tu nueva contraseña temporal es: ' || l_nueva || CHR(10) || CHR(10) ||
                   'Por seguridad, cambiala al ingresar (Ajustes > Seguridad y contraseña).' || CHR(10) ||
                   'Usuario: ' || l_user || CHR(10) || CHR(10) ||
                   'Si no lo pediste vos, podés volver a dar de baja la cuenta desde Ajustes.'
    );
  END pr_reactivar_correo;

END PKG_LT_CUENTA;
/


--------------------------------------------------------------------------------
-- 3. ORDS · PLANTILLAS /lt/cuenta/*
--
-- Se agregan al módulo `lt` SIN redefinirlo (DEFINE_MODULE borraría los demás
-- endpoints). Mismo estilo que los handlers de lt/autenticacion.
--------------------------------------------------------------------------------

DECLARE
  -- Una plantilla POST con su handler y el status de salida.
  PROCEDURE definir(p_patron IN VARCHAR2, p_fuente IN VARCHAR2) IS
  BEGIN
    ORDS.DEFINE_TEMPLATE(p_module_name => 'lt', p_pattern => p_patron);
    ORDS.DEFINE_HANDLER(
      p_module_name => 'lt',
      p_pattern     => p_patron,
      p_method      => 'POST',
      p_source_type => ORDS.source_type_plsql,
      p_source      => p_fuente
    );
    ORDS.DEFINE_PARAMETER(
      p_module_name => 'lt', p_pattern => p_patron, p_method => 'POST',
      p_name => 'X-APEX-STATUS-CODE', p_bind_variable_name => 'status_code',
      p_source_type => 'HEADER', p_param_type => 'INT', p_access_method => 'OUT');
  END definir;
BEGIN
  ------------------------------------------------------------------------------
  -- POST /lt/cuenta/inactivar — Bearer
  ------------------------------------------------------------------------------
  definir('cuenta/inactivar', q'~
BEGIN
    APEX_JSON.PARSE(:body_text);
    PKG_LT_CUENTA.pr_inactivar(
        p_token    => :token_hdr,
        p_password => APEX_JSON.GET_VARCHAR2('password'),
        p_motivo   => APEX_JSON.GET_VARCHAR2('motivo')
    );
    COMMIT;
    :status_code := 200;
    APEX_JSON.OPEN_OBJECT;
    APEX_JSON.WRITE('ok', TRUE);
    APEX_JSON.WRITE('mensaje', 'Tu cuenta fue dada de baja.');
    APEX_JSON.CLOSE_OBJECT;
EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    :status_code := CASE SQLCODE WHEN -20401 THEN 401 ELSE 400 END;
    APEX_JSON.OPEN_OBJECT;
    APEX_JSON.WRITE('ok', FALSE);
    APEX_JSON.WRITE('error', SQLERRM);
    APEX_JSON.CLOSE_OBJECT;
END;
~');
  ORDS.DEFINE_PARAMETER(
    p_module_name => 'lt', p_pattern => 'cuenta/inactivar', p_method => 'POST',
    p_name => 'Authorization', p_bind_variable_name => 'token_hdr',
    p_source_type => 'HEADER', p_param_type => 'STRING', p_access_method => 'IN');

  ------------------------------------------------------------------------------
  -- POST /lt/cuenta/estado — sin sesión (lo usa la pantalla de registro)
  ------------------------------------------------------------------------------
  definir('cuenta/estado', q'~
BEGIN
    APEX_JSON.PARSE(:body_text);
    :status_code := 200;
    APEX_JSON.OPEN_OBJECT;
    APEX_JSON.WRITE('ok', TRUE);
    APEX_JSON.WRITE('inactiva', PKG_LT_CUENTA.fn_inactiva(APEX_JSON.GET_VARCHAR2('email')) = 'S');
    APEX_JSON.CLOSE_OBJECT;
EXCEPTION WHEN OTHERS THEN
    :status_code := 400;
    APEX_JSON.OPEN_OBJECT;
    APEX_JSON.WRITE('ok', FALSE);
    APEX_JSON.WRITE('error', SQLERRM);
    APEX_JSON.CLOSE_OBJECT;
END;
~');

  ------------------------------------------------------------------------------
  -- POST /lt/cuenta/reactivar — sin sesión, con la contraseña de la cuenta
  ------------------------------------------------------------------------------
  definir('cuenta/reactivar', q'~
BEGIN
    APEX_JSON.PARSE(:body_text);
    PKG_LT_CUENTA.pr_reactivar(
        p_email    => APEX_JSON.GET_VARCHAR2('email'),
        p_password => APEX_JSON.GET_VARCHAR2('password')
    );
    COMMIT;
    :status_code := 200;
    APEX_JSON.OPEN_OBJECT;
    APEX_JSON.WRITE('ok', TRUE);
    APEX_JSON.WRITE('mensaje', 'Tu cuenta fue reactivada.');
    APEX_JSON.CLOSE_OBJECT;
EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    :status_code := 400;
    APEX_JSON.OPEN_OBJECT;
    APEX_JSON.WRITE('ok', FALSE);
    APEX_JSON.WRITE('error', SQLERRM);
    APEX_JSON.CLOSE_OBJECT;
END;
~');

  ------------------------------------------------------------------------------
  -- POST /lt/cuenta/reactivar-correo — sin sesión; responde siempre lo mismo
  ------------------------------------------------------------------------------
  definir('cuenta/reactivar-correo', q'~
BEGIN
    APEX_JSON.PARSE(:body_text);
    PKG_LT_CUENTA.pr_reactivar_correo(p_email => APEX_JSON.GET_VARCHAR2('email'));
    COMMIT;
    PKG_AUTH.pr_flush_correo;
    :status_code := 200;
    APEX_JSON.OPEN_OBJECT;
    APEX_JSON.WRITE('ok', TRUE);
    APEX_JSON.WRITE('mensaje', 'Si el correo corresponde a una cuenta dada de baja, te enviamos una contraseña nueva.');
    APEX_JSON.CLOSE_OBJECT;
EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    :status_code := 400;
    APEX_JSON.OPEN_OBJECT;
    APEX_JSON.WRITE('ok', FALSE);
    APEX_JSON.WRITE('error', SQLERRM);
    APEX_JSON.CLOSE_OBJECT;
END;
~');

  COMMIT;
END;
/


--------------------------------------------------------------------------------
-- 4. VERIFICACIÓN
--------------------------------------------------------------------------------

BEGIN
  FOR o IN (SELECT object_name, object_type, status FROM user_objects
             WHERE object_name IN ('PKG_LT_CUENTA', 'LT_CUENTAS_BAJAS')
             ORDER BY object_type) LOOP
    IF o.status = 'VALID' THEN
      DBMS_OUTPUT.PUT_LINE('[OK]   ' || o.object_type || ' ' || o.object_name);
    ELSE
      DBMS_OUTPUT.PUT_LINE('[ERROR] ' || o.object_type || ' ' || o.object_name || ' quedo INVALID:');
      FOR e IN (SELECT line, text FROM user_errors
                 WHERE name = o.object_name AND type = o.object_type ORDER BY sequence) LOOP
        DBMS_OUTPUT.PUT_LINE('        L' || e.line || ': ' || e.text);
      END LOOP;
    END IF;
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('       POST   /lt/cuenta/inactivar');
  DBMS_OUTPUT.PUT_LINE('       POST   /lt/cuenta/estado');
  DBMS_OUTPUT.PUT_LINE('       POST   /lt/cuenta/reactivar');
  DBMS_OUTPUT.PUT_LINE('       POST   /lt/cuenta/reactivar-correo');
END;
